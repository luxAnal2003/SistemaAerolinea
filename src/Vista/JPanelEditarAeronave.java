    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        String modelo = txtModelo.getText().trim();
        int capacidad = (int) SpinCapacidad.getValue();
        String estado= cbxEstado.getSelectedItem().toString();
        Aeronave aeronave = new Aeronave();
        aeronave.setModelo(modelo);
        aeronave.setCapacidad(capacidad);
        aeronave.setEstado(estado);
        boolean registrado = aeroController.actualizarAeronave(aeronave, idAero);

        if (registrado) {
            JOptionPane.showMessageDialog(
                    this,
                    "Aeronave actualizada correctamente"
            );
            setear();
            cargarAeronavesEnTabla();
        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "Error al actualizar aeronave"
            );
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

