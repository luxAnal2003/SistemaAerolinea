    private void buscarAeronave() {
        String criterio = txtBuscador.getText().trim();

        if (criterio.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Ingrese un criterio de búsqueda");
            cargarAeronavesEnTabla();
            return;
        }

        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(new Object[]{"ID", "Modelo", "Capacidad", "Estado"});

        List<Aeronave> aeronavesEncontradas = aeroController.buscarAeronave(criterio);

        if (!aeronavesEncontradas.isEmpty()) {
            for (Aeronave aero : aeronavesEncontradas) {
                Object[] fila = new Object[8];
                fila[0] = aero.getIdAeronave();
                fila[1] = aero.getModelo();
                fila[2] = aero.getCapacidad();
                model.addRow(fila);
            }
            tableAeronave.setModel(model);
            jScrollPane1.setViewportView(tableAeronave);
        } else {
            JOptionPane.showMessageDialog(null, "No se encontraron resultados");
            cargarAeronavesEnTabla();
        }
    }

    private void cargarAeronavesEnTabla() {
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(
                new Object[]{
                    "ID",
                    "Modelo",
                    "Capacidad",
                    "Estado"
                }
        );

        List<Aeronave> aeronaves
                = aeroController.listarAeronaves();

        for (Aeronave a : aeronaves) {

            model.addRow(new Object[]{
                a.getIdAeronave(),
                a.getModelo(),
                a.getCapacidad(),
                a.getEstado()
            });
        }

        tableAeronave.setModel(model);
        tableAeronave.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                int fila = tableAeronave.getSelectedRow();
                if (fila != -1) {
                    idAero = Integer.parseInt(tableAeronave.getValueAt(fila, 0).toString());
                    enviarDatosCliente(idAero);
                }
            }
        });
    }
    
    private void enviarDatosCliente(int idAero) {
        Aeronave aero = aeroController.obtenerAeronavePorId(idAero);

        if (aero != null) {
            txtModelo.setText(aero.getModelo());
            SpinCapacidad.setValue(aero.getCapacidad());
            cbxEstado.setSelectedItem(aero.getEstado());
        } else {
            JOptionPane.showMessageDialog(null, "No se encontró la aeronave seleccionada.");
            setear();
        }
    }
